// Reference renders the full settings table for `screenai settings`
// and the README.
func Reference() string {
	var b strings.Builder
	b.WriteString("Screen AI settings reference\n\n")
	b.WriteString("Apply with --set key=value (repeatable), --langs, --min-conf,\n")
	b.WriteString("or a JSON file: --settings FILE, or ./settings.json which is\n")
	b.WriteString("auto-loaded (create one with `screenai init`).\n\n")
	for _, group := range []struct{ title, prefix string }{
		{"OCR (Google's closed-source gocr engine)", "ocr."},
		{"MCE (Screen2x main-content model)", "mce."},
		{"Reader view (main-content export, wrapper side)", "reader."},
		{"Report (HTML report overlays, wrapper side)", "report."},
	} {
		b.WriteString(group.title + "\n")
		for _, d := range Descriptors {
			if !strings.HasPrefix(d.Key, group.prefix) {
				continue
			}
			fmt.Fprintf(&b, "  %-38s %-6s default %-8s [%s]\n", d.Key, d.Type, d.Default, d.Mechanism)
			fmt.Fprintf(&b, "    %s\n", d.Summary)
			fmt.Fprintf(&b, "    %s\n", d.Effect)
		}
		b.WriteString("\n")
	}
	b.WriteString("Script codes for ocr.scripts: Arab Beng Cyrl Deva Geor Grek Gujr Guru\n")
	b.WriteString("Hani Hebr Jpan Khmr Knda Kore Laoo Mlym Sinh Taml Telu Thai und.\n")
	b.WriteString("Language codes (en, ru, ja, ...) are accepted too and mapped to\n")
	b.WriteString("scripts; Latin languages ride on the 'und' universal recognizer.\n")
	b.WriteString("Engine-level settings are read once per process (the library\n")
	b.WriteString("caches its configs); wrapper-side filters are per-run.\n")
	return b.String()
}

// ReferenceJSON renders the settings reference as machine-readable
// JSON (used by `screenai settings --json`).
func ReferenceJSON() string {
	docs := make([]map[string]any, 0, len(Descriptors))
	for _, d := range Descriptors {
		docs = append(docs, map[string]any{
			"key":       d.Key,
			"type":      d.Type,
			"default":   d.Default,
			"mechanism": string(d.Mechanism),
			"summary":   d.Summary,
			"effect":    d.Effect,
		})
	}
	b, err := json.MarshalIndent(map[string]any{
		"ok":          true,
		"settings":    docs,
		"template":    Template(),
		"auto_loaded": DiscoverPaths(),
		"auto_note":   "screenai init writes a documented settings.json; ./settings.json is auto-loaded",
	}, "", "  ")
	if err != nil {
		return "{}"
	}
	return string(b)
}

// DiscoverPaths lists the paths checked for the auto-loaded settings
// file, in precedence order.
func DiscoverPaths() []string {
	paths := []string{}
	if env := os.Getenv("SCREENAI_SETTINGS"); env != "" {
		paths = append(paths, env)
	}
	paths = append(paths, "settings.json", "screenai.settings.json")
	return paths
}
