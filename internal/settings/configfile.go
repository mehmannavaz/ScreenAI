package settings

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

// LoadJSONFile reads a settings file (settings.json). Two formats are
// accepted — flat keys:
//
//	{
//	  "mce.threshold_non_essential": 0.99,
//	  "ocr.scripts": "und,Jpan,Kore,Hani",
//	  "ocr.languages": ["en", "de"]
//	}
//
// or nested groups (recommended — this is what `screenai init` writes):
//
//	{
//	  "ocr": {
//	    "min_confidence": 0.8,
//	    "languages": ["en"]
//	  },
//	  "mce": {
//	    "threshold_non_essential": 0.99,
//	    "crop_main": true
//	  },
//	  "reader": { "format": "markdown" }
//	}
//
// The two may also be mixed. Keys that start with '_' are
// documentation and are ignored at any level, which is how the
// generated template explains itself. An empty string or empty array
// value means "leave unset". Keys are applied in sorted order (a file
// must not depend on order anyway) and unknown keys fail loudly,
// exactly like --set.
func LoadJSONFile(path string, into *Settings) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("settings file: %v", err)
	}
	pairs, err := parseJSONSettings(raw)
	if err != nil {
		return fmt.Errorf("settings file %s: %v", path, err)
	}
	sort.Slice(pairs, func(i, j int) bool { return pairs[i].key < pairs[j].key })
	for _, p := range pairs {
		if p.value == "" { // empty value = explicitly unset
			continue
		}
		if err := into.Set(p.key, p.value); err != nil {
			return fmt.Errorf("settings file %s: %v", path, err)
		}
	}
	return nil
}

type kvPair struct {
	key, value string
}

// parseJSONSettings flattens the flat/nested document into key/value
// pairs, dropping '_'-prefixed documentation keys.
func parseJSONSettings(raw []byte) ([]kvPair, error) {
	var doc map[string]json.RawMessage
	if err := json.Unmarshal(raw, &doc); err != nil {
		return nil, err
	}
	var out []kvPair
	for k, v := range doc {
		if isDocKey(k) {
			continue
		}
		pairs, err := flattenValue(k, v)
		if err != nil {
			return nil, err
		}
		out = append(out, pairs...)
	}
	return out, nil
}

// flattenValue turns one top-level entry into pairs: a plain value
// becomes key=value; an object becomes its "group.subkey" children.
func flattenValue(key string, raw json.RawMessage) ([]kvPair, error) {
	trimmed := strings.TrimSpace(string(raw))
	if strings.HasPrefix(trimmed, "{") {
		var group map[string]json.RawMessage
		if err := json.Unmarshal(raw, &group); err != nil {
			return nil, fmt.Errorf("%s: %v", key, err)
		}
		var out []kvPair
		for sub, v := range group {
			if isDocKey(sub) {
				continue
			}
			if isDocKey(key) { // a "_doc" group — skip whole
				continue
			}
			subTrimmed := strings.TrimSpace(string(v))
			if strings.HasPrefix(subTrimmed, "{") {
				return nil, fmt.Errorf("%s.%s: nested groups are one level deep", key, sub)
			}
			value, err := jsonToValue(v)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %v", key, sub, err)
			}
			out = append(out, kvPair{key: key + "." + sub, value: value})
		}
		return out, nil
	}
	value, err := jsonToValue(raw)
	if err != nil {
		return nil, fmt.Errorf("%s: %v", key, err)
	}
	return []kvPair{{key: key, value: value}}, nil
}

// isDocKey reports whether a key is '_'-prefixed documentation.
func isDocKey(k string) bool {
	return strings.HasPrefix(k, "_")
}

func jsonToValue(raw json.RawMessage) (string, error) {
	trimmed := strings.TrimSpace(string(raw))
	switch {
	case trimmed == "null":
		return "", fmt.Errorf("null is not a settings value")
	case trimmed == "":
		return "", fmt.Errorf("empty value")
	case strings.HasPrefix(trimmed, "\""):
		var s string
		if err := json.Unmarshal(raw, &s); err != nil {
			return "", err
		}
		return s, nil
	case strings.HasPrefix(trimmed, "["):
		var arr []string
		if err := json.Unmarshal(raw, &arr); err != nil {
			// try numbers inside the array
			var nums []json.Number
			if err2 := json.Unmarshal(raw, &nums); err2 != nil {
				return "", err
			}
			parts := make([]string, len(nums))
			for i, n := range nums {
				parts[i] = n.String()
			}
			return strings.Join(parts, ","), nil
		}
		return strings.Join(arr, ","), nil
	default:
		// booleans and numbers pass through as their literal text
		return trimmed, nil
	}
}

